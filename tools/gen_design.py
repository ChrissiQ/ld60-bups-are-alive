def icon_tiles(name, use, uses, rest):
    """One tile per colour the icon is drawn in; the label names the context when there is more than one."""
    by_colour = {}
    for v in icon_holders(name, uses): by_colour.setdefault(rest.get(v), []).append(v)
    tiles = ""
    for rgba, holders in by_colour.items():
        label = use
        if len(by_colour) > 1:
            label += " (%s)" % next(ICON_CONTEXT[(name, v)] for v in holders if (name, v) in ICON_CONTEXT)
        tiles += '<div class="tile">%s<span class="label">%s</span><code>%s.svg</code></div>' % (icon_svg(name, ICON_SPECIMEN_PX, rgba), e(label), name)
    return tiles

def natural(label):
    """Sort key: alphabetical, with numbers in numeric order (x1, x100, x1,000)."""
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", label.lower().replace(",", ""))]

