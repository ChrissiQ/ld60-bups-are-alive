GROUNDS = ["surface_solid", "raised", "sunken"]

def cell(t, ground):
    r = contrast(t["rgba"], COL[ground])
    need = TEXT_MIN if t["use"] == "text" else GRAPHIC_MIN
    return '<td><span class="ratio %s">%.1f:1</span></td>' % ("pass" if r >= need else "fail", r)

def access_section():
    fg = [t for g in D["colors"] for t in g["tokens"] if t.get("use")]
    body = "".join('<tr><td><span class="sw"><span style="background:var(--%s)"></span></span></td><td><code>%s</code></td><td class="num">%s</td>%s</tr>'
                   % (css(t["name"]), t["name"], "text 4.5:1" if t["use"] == "text" else "non-text 3:1", "".join(cell(t, g) for g in GROUNDS)) for t in fg)
    head = ["", "Token", "Needs"] + ["on <code>%s</code>" % g for g in GROUNDS]
    src = ('<p class="note">Checked against the Xbox Accessibility Guidelines: '
           '<a href="https://devdocs.xbox.com/gaming/accessibility/xbox-accessibility-guidelines/101">101, text display</a>; '
           '<a href="https://devdocs.xbox.com/gaming/accessibility/xbox-accessibility-guidelines/102">102, contrast</a>.</p>')
    faint = next(t for t in fg if t["name"] == "faint")
    gap = ""
    if contrast(faint["rgba"]) < TEXT_MIN:
        gap = '<p class="note"><code>faint</code> is %.1f:1 on the panel fill but carries units, which are small text and need 4.5:1.</p>' % contrast(faint["rgba"])
    contrast_part = ('<div class="group" id="a-contrast"><h3>Contrast</h3><p class="note">Text needs 4.5:1; large text, inactive text and non-text marks need 3:1. '
                     'Failures are outlined. Translucent fills are omitted: their ground is the dish.</p>%s%s</div>'
                     % (table(head, body, ["4.5rem", "13rem", "7rem", "11rem", "11rem", None]), gap))
    size_part = ('<div class="group" id="a-text"><h3>Text size</h3><p class="note">Minimum body height (ascender to descender) is %d px on a 1080p PC screen, and text must scale to %s. '
                 'Failures are below the minimum at 100%%.</p>%s</div>'
                 % (TEXT_BODY_MIN, pct(SCALE_NEEDED), text_size_table()))
    return src + size_part + contrast_part

