def icon_uses():
    """icon name -> theme variations of the nodes whose scene gives them that icon."""
    uses = {}
    for folder in ("scenes", "ui"):
        for f in sorted(os.listdir(folder)):
            if not f.endswith(".tscn"): continue
            t = open(os.path.join(folder, f)).read()
            ids = {m.group(2): m.group(1) for m in re.finditer(r'\[ext_resource[^\]]*path="res://icons/(\w+)\.svg" id="([^"]+)"', t)}
            for blk in re.split(r"\n(?=\[node)", t):
                var = re.search(r'theme_type_variation = &?"(\w+)"', blk)
                for i, name in ids.items():
                    if var and re.search(r'\bicon = ExtResource\("%s"\)' % re.escape(i), blk): uses.setdefault(name, []).append(var.group(1))
    return uses

ICON_SPECIMEN_PX = 24  # one size for every specimen, so the page says nothing of the icon sizes

def resting_colours():
    """theme variation -> the colour its icon has at rest, from the generated theme (Godot draws an icon white when the theme sets none)."""
    with open("scenes/menu_theme.tres") as f:
        return {m.group(1): tuple(round(float(x), 2) for x in m.group(2).split(",")) for m in re.finditer(r"^(\w+)/colors/icon_normal_color = Color\(([^)]*)\)", f.read(), re.M)}

def icon_svg(name, px, rgba):
    svg = open("icons/%s.svg" % name).read().strip()
    svg = re.sub(r' (?:width|height)="\d+"', "", svg, count=2)
    colour = "white" if rgba is None else "rgb(%d,%d,%d)" % tuple(round(x * 255) for x in rgba[:3])  # Godot draws an icon white when the theme sets no colour
    return svg.replace("#ffffff", "currentColor").replace("<svg ", '<svg class="glyph" style="width:%srem;height:%srem;color:%s" ' % (rem(px), rem(px), colour), 1)

def icon_holders(name, uses):
    """The theme variations that hold the icon."""
    return sorted(set(uses.get(name, [])) | ({ICON_FALLBACK[name]} if name in ICON_FALLBACK else set()))

