def ratio_badge(t):
    use = t.get("use")
    if not use: return ""
    need = TEXT_MIN if use == "text" else GRAPHIC_MIN
    r = contrast(t["rgba"])
    return '<span class="ratio %s" title="%s">%.1f:1</span>' % ("pass" if r >= need else "fail", "Text needs 4.5:1" if use == "text" else "Graphic needs 3:1", r)

