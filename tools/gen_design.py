def setting(name):
    """A number from scripts/user_settings.gd, so the page never repeats it."""
    with open("scripts/user_settings.gd") as f: m = re.search(r"^const %s := ([0-9.]+)" % name, f.read(), re.M)
    return float(m.group(1))
def gd(path, name):
    """A constant from a game script, so the page never repeats it: a number, or a tuple for a vector."""
    with open(path) as f: m = re.search(r"^const %s := (.+?)(?:  ##.*)?$" % name, f.read(), re.M)
    v = [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", re.sub(r"^\w+\(", "(", m.group(1)))]
    return v[0] if len(v) == 1 else tuple(v)

def num(x): return "%g" % x
def secs(x): return num(x) + " s"
