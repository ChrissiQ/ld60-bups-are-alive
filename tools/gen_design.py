    rows = "".join("<tr><td><code>%s</code></td><td class=\"num\">%d px</td>%s%s<td>%s</td></tr>" % (x["name"], x["px"], cell(x["px"], PLEX_FACTOR, "text"), cell(x["px"], MONO_FACTOR, "mono"), e(x["role"])) for x in TYPE["sizes"])
