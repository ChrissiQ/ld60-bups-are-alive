def rem(px): return "%g" % (px / 16)  # 1rem is 16 px, the game's text size at 100%

def css(name): return name.replace("_", "-")

def over(c, ground):
    a = c[3]
    return tuple(c[i] * a + ground[i] * (1 - a) for i in range(3))

def luminance(rgb):
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (f(v) for v in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast(c, ground=GROUND):
    a, b = sorted((luminance(over(c, ground[:3])), luminance(ground[:3])), reverse=True)
    return (a + 0.05) / (b + 0.05)

